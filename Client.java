    public void sendMess(String mess) throws IOException{
        os.write(mess);
        os.newLine();
        os.flush();
    }
    
    public void setupSocket(){
        try{
            Socket client = new Socket("localhost", 5000);
            System.out.println("Client ket noi thanh cong.");
            is = new BufferedReader(new InputStreamReader(client.getInputStream()));
            os = new BufferedWriter(new OutputStreamWriter(client.getOutputStream()));
            String mess;
            while(true){
                mess = is.readLine();
                if(mess.isEmpty()){
                    break;
                }
                String[] messSplit = mess.split(",.");
                if(messSplit[0].equals("setId")){
                    setId(Integer.parseInt(messSplit[1]));
                }
                if(messSplit[0].equals("updateComboBox")){
                    listOnline = new ArrayList<>();
                    String online = "";
                    for(int i = 1;i < messSplit.length;i++){
                        listOnline.add(messSplit[i]);
                        if(id != Integer.parseInt(messSplit[i]))    online += "---Client " + messSplit[i] + " : online---\n";
                    }
                    jTextArea5.setText(online);
                    updateComboBox();
                }
                if(messSplit[0].equals("global")){
                    jTextArea1.setText(jTextArea1.getText() + messSplit[1] + "\n");
                }
                if(messSplit[0].equals("personTOperson")){
                    jTextArea1.setText(jTextArea1.getText() + messSplit[1] + "\n");
                }
            }
        }catch (Exception e){
            e.printStackTrace();
        }
    }
    
