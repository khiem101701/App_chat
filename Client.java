    public void updateComboBox(){
        jComboBox1.removeAllItems();
        jComboBox1.addItem("Gui tat ca");
        String strId = ""+id;
        for(String x : listOnline){
            if(!strId.equals(x)){
                jComboBox1.addItem("Client " + x);
            }
        }
    }
    
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        String mess = jTextField1.getText();
        if(jTextField1.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane, "Ban chua nhap tin nhan!");
            return;
        }
        if(jComboBox1.getSelectedIndex() == 0){
            try{
                jTextArea1.setText(jTextArea1.getText() + "Ban : " + jTextField1.getText() + "\n");
                sendMess("global,."+mess+",."+id);
            }
            catch (IOException ioe){
                JOptionPane.showMessageDialog(rootPane, "Error!");
            }
        }
        else{
            try{
                jTextArea1.setText(jTextArea1.getText() + "Ban(den "+jComboBox1.getSelectedItem().toString().toLowerCase()+"): "+jTextField1.getText()+"\n");
                String[] strSplit = jComboBox1.getSelectedItem().toString().split(" ");
                //id nguoi gui
                //strSplit[1] nguoi nhan
                sendMess("personTOperson,."+mess+",."+id+",."+strSplit[1]);
            }
            catch (IOException ioe){
                JOptionPane.showMessageDialog(rootPane, "Error!");
            }
        }
        jTextField1.setText("");
        jTextField1.requestFocus();
    }                                        

